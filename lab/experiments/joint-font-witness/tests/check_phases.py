#!/usr/bin/env python3
"""Independent validation of aggregated inclusive phases and matched counters.

Input files are evidence supplied by C, never generated by this checker.
No wall-clock gain threshold is asserted. Inclusive phases are not partitions.
"""
import argparse
import csv
from collections import defaultdict
from pathlib import Path

TIMERS = set('''catalog.access catalog.initialize
session.total session.lock_wait session.probe_before session.initial_fast_verify
session.initial_key_check session.prepare session.prepared_check session.reuse_verify
session.build session.final_key_check session.final_fast_verify
fast.key fast.verify fast.config fast.walk_roots fast.roots_recheck fast.config_bytes_recheck
prepare.total prepare.from_database prepare.collect_stamps discovery.fontdb_load_system
project.discovery generation.unchanged catalog.prepared_build catalog.fresh_build
catalog.acquire_selective_coverage catalog.embedded catalog.compose catalog.project_book
source.access pipeline.paged pipeline.eval pipeline.pdf_export'''.split())
EVENTS = set('''event.cycle event.session.cold event.session.warm event.session.reuse_fast
 event.session.reuse_prepared event.session.published_new event.session.fallback_poisoned
 event.session.fallback_prepare event.session.fallback_prepared_changed
 event.session.fallback_final_changed'''.split())
# Alternatives are summed ONLY to bound an aggregated label emitted at several
# sites. This is never interpreted as an additive runtime decomposition.
PARENTS = {
    'catalog.initialize': ['catalog.access'],
    'session.total': ['catalog.initialize'],
    'catalog.fresh_build': ['catalog.initialize'],
    'fast.key': ['session.probe_before'],
    'fast.verify': ['session.initial_fast_verify', 'session.reuse_verify', 'session.final_fast_verify'],
    'fast.config': ['fast.key', 'fast.verify'],
    'fast.walk_roots': ['fast.key'],
    'fast.roots_recheck': ['fast.walk_roots', 'fast.verify'],
    'fast.config_bytes_recheck': ['fast.key'],
    'prepare.total': ['session.prepare'],
    'prepare.from_database': ['prepare.total'],
    'prepare.collect_stamps': ['prepare.from_database'],
    'discovery.fontdb_load_system': ['prepare.total', 'catalog.fresh_build'],
    'project.discovery': ['prepare.from_database', 'catalog.fresh_build'],
    'generation.unchanged': ['prepare.from_database', 'session.initial_key_check', 'session.prepared_check', 'session.final_key_check'],
    'catalog.prepared_build': ['session.build'],
    'catalog.acquire_selective_coverage': ['catalog.prepared_build', 'catalog.fresh_build'],
    'catalog.embedded': ['catalog.prepared_build', 'catalog.fresh_build'],
    'catalog.compose': ['catalog.prepared_build', 'catalog.fresh_build'],
    'catalog.project_book': ['catalog.compose'],
    'pipeline.eval': ['pipeline.paged'],
}
for label in TIMERS:
    if label.startswith('session.') and label != 'session.total':
        PARENTS[label] = ['session.total']

# Additional joint scopes are alternatives at the same existing call sites.
TIMERS.update("""joint.session joint.lock_wait joint.establish joint.establish_discover
joint.capture joint.config_context joint.discovery joint.evidence_selfcheck joint.g1_prepare
joint.g2 joint.build joint.g3 joint.policy""".split())
EVENTS.update("""event.joint.cold event.joint.warm event.joint.poisoned
 event.joint.established event.joint.decline event.joint.fallback_standard
 event.joint.capture_lstat event.joint.capture_stat""".split())
PARENTS.update({
    'joint.session': ['catalog.initialize'],
    'joint.lock_wait': ['joint.session'],
    'joint.establish': ['joint.session'],
    'joint.establish_discover': ['joint.establish'],
    'joint.capture': ['joint.establish_discover'],
    'joint.config_context': ['joint.capture'],
    'joint.discovery': ['joint.capture'],
    'joint.evidence_selfcheck': ['joint.capture'],
    'joint.g1_prepare': ['joint.establish_discover'],
    'joint.g2': ['joint.establish'],
    'joint.build': ['joint.establish'],
    'joint.g3': ['joint.establish'],
    'joint.policy': ['joint.establish'],
})
PARENTS['fast.config'].append('joint.establish_discover')
PARENTS['fast.verify'].append('joint.policy')
PARENTS['prepare.from_database'].append('joint.g1_prepare')
PARENTS['generation.unchanged'].extend(['joint.g2', 'joint.g3'])
PARENTS['catalog.prepared_build'].append('joint.build')


def require(condition, message):
    if not condition:
        raise ValueError(message)


def natural(raw, name, positive=False):
    require(raw.isascii() and raw.isdecimal(), f'invalid {name}: {raw!r}')
    value = int(raw)
    require(not positive or value > 0, f'{name} must be positive')
    return value


def parse_phases(text):
    groups = defaultdict(dict)
    last_cycle = {}
    for number, row in enumerate(csv.reader(text.splitlines(), delimiter='\t'), 1):
        require(len(row) == 5, f'TSV row {number}: expected five columns')
        pid = natural(row[0], 'pid', True)
        cycle = natural(row[1], 'cycle')
        label = row[2]
        calls = natural(row[3], 'calls', True)
        ns = natural(row[4], 'ns')
        require(label in TIMERS | EVENTS, f'unknown label {label!r}')
        require(cycle >= last_cycle.get(pid, cycle), f'cycle went backwards for pid={pid}')
        last_cycle[pid] = cycle
        key = (pid, cycle)
        require(label not in groups[key], f'duplicate label {key} {label}')
        require(label not in EVENTS or ns == 0, f'event duration must be zero: {label}')
        groups[key][label] = (calls, ns)
    require(groups, 'empty phase evidence')
    for key, rows in groups.items():
        def count(label): return rows.get(label, (0, 0))[0]
        require(count('event.cycle') == 1, f'{key}: missing/surplus cycle publication')
        total = count('session.total')
        cold = count('event.session.cold')
        warm = count('event.session.warm')
        poisoned = count('event.session.fallback_poisoned')
        fast = count('event.session.reuse_fast')
        fallback_prepare = count('event.session.fallback_prepare')
        fallback_changed = count('event.session.fallback_prepared_changed')
        published = count('event.session.published_new')
        final_changed = count('event.session.fallback_final_changed')
        prepared_reuse = count('event.session.reuse_prepared')
        def equal(label, expected):
            require(count(label) == expected, f'{key}: {label}={count(label)}, expected {expected}')
        equal('session.total', cold + warm + poisoned)
        require(total == fast + prepared_reuse + published + poisoned + fallback_prepare + fallback_changed + final_changed,
                f'{key}: exactly one terminal outcome is required per session')
        equal('session.lock_wait', total)
        equal('session.initial_fast_verify', warm)
        require(count('session.initial_key_check') <= warm, f'{key}: key check bypassed warm short-circuit')
        require(fast <= warm, f'{key}: cold session cannot use fast reuse')
        prepared = total - fast - poisoned
        equal('session.prepare', prepared)
        equal('session.probe_before', prepared)
        equal('session.prepared_check', prepared - fallback_prepare)
        equal('session.build', published + final_changed)
        equal('session.final_key_check', count('session.build'))
        require(count('session.final_fast_verify') <= count('session.build'), f'{key}: final fast verify without build')
        if count('joint.session'):
            joint_total = count('joint.session')
            joint_cold = count('event.joint.cold')
            joint_warm = count('event.joint.warm')
            joint_poisoned = count('event.joint.poisoned')
            established = count('event.joint.established')
            decline = count('event.joint.decline')
            equal('joint.session', joint_cold + joint_warm + joint_poisoned)
            equal('joint.lock_wait', joint_total)
            equal('joint.establish', joint_cold)
            equal('joint.establish_discover', joint_cold)
            require(established + decline == joint_cold, f'{key}: every joint cold attempt needs one terminal outcome')
            equal('event.joint.fallback_standard', joint_warm + joint_poisoned + decline)
            equal('session.total', count('event.joint.fallback_standard'))
            require(count('joint.capture') <= joint_cold, f'{key}: capture outside a cold attempt')
            require(count('joint.g1_prepare') <= count('joint.capture'), f'{key}: G1 without capture')
            require(count('joint.g2') <= count('joint.g1_prepare'), f'{key}: G2 without successful discovery')
            require(count('joint.build') <= count('joint.g2'), f'{key}: build bypassed G2')
            equal('joint.g3', count('joint.build'))
            require(count('joint.policy') <= count('joint.g3'), f'{key}: policy bypassed G3')
            require(established <= count('joint.policy'), f'{key}: publication bypassed policy')
            require(count('event.joint.capture_stat') <= count('event.joint.capture_lstat'), f'{key}: target stat attempts exceed lstat attempts')
        else:
            require(not any(label.startswith('event.joint.') for label in rows), f'{key}: joint event without joint session')
        for child, parents in PARENTS.items():
            if child in rows:
                parent_ns = sum(rows.get(parent, (0, 0))[1] for parent in parents)
                parent_calls = sum(count(parent) for parent in parents)
                require(parent_calls > 0, f'{key}: {child} has no enclosing scope among {parents}')
                require(rows[child][1] <= parent_ns, f'{key}: inclusive duration of {child} exceeds enclosing scopes {parents}')
        # Zero sessions is legitimate for independent fresh CLI worlds. No rule
        # assumes that the host is eligible for a fast fontconfig proof.
    return groups


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('phases', type=Path)
    args = parser.parse_args()
    groups = parse_phases(args.phases.read_text())
    print(f'phases validated: {len(groups)} process/cycle groups; inclusive scopes, never a partition')


if __name__ == '__main__':
    main()
