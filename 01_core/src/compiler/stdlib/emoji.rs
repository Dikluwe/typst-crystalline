/// Constrói o `Value::Module` que representa o módulo `emoji` no scope.
///
/// Paridade vanilla — medido: `type(emoji)` → `module`.
pub fn build_emoji_module() -> Value {
    let mut scope = crate::entities::scope::Scope::new();
    for (name, ch) in EMOJI_TABLE {
        scope.define(*name, Value::Symbol(Symbol::new(*ch, *name)));
    }
    for (name, value, variants) in EMOJI_GROUPS {
        scope.define(
            *name,
            Value::Symbol(Symbol::with_variants(*value, *name, variants())),
        );
    }
    Value::Module(crate::entities::module::Module::new("emoji", scope))
}
